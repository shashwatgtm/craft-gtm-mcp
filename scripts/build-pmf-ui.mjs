import fs from 'node:fs';
import { tools } from '../dist/tools.js';
const schema = tools.find(tool => tool.name === 'pmf_scorecard').inputSchema;
const htmlPath = new URL('../ui/pmf-scorecard.html', import.meta.url);
const html = fs.readFileSync(htmlPath, 'utf8').replace(/\/\*PMF_SCHEMA_START\*\/[\s\S]*?\/\*PMF_SCHEMA_END\*\//, '/*PMF_SCHEMA_START*/'+JSON.stringify(schema).replace(/</g,'\\u003c')+'/*PMF_SCHEMA_END*/');
fs.writeFileSync(htmlPath, html);
const source = '// Generated by scripts/build-pmf-ui.mjs. Do not edit.\n'
  + 'export const PMF_UI_URI = "ui://helix/pmf-scorecard/v1.html";\n'
  + 'export const PMF_UI_MIME = "text/html;profile=mcp-app";\n'
  + 'export const PMF_UI_META = { ui: { csp: { connectDomains: [], resourceDomains: [], frameDomains: [] } } };\n'
  + 'export const PMF_UI_HTML = '+JSON.stringify(html)+';\n';
fs.writeFileSync(new URL('../src/pmf-ui.ts', import.meta.url), source);
console.log('Generated PMF resource from the current tool schema.');
